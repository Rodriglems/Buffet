export function consolidarCardapio(itens = CARDAPIO_CHEF_RAY) {
  const mapa = new Map();
  for (const item of itens) {
    const existente = mapa.get(item.nome);
    if (!existente) {
      mapa.set(item.nome, { ...item });
      continue;
    }
    existente.cardapios = [...new Set([...existente.cardapios, ...item.cardapios])];
    if (!existente.descricao && item.descricao) existente.descricao = item.descricao;
    if (Number(existente.precoBase) === 0 && Number(item.precoBase) > 0) {
      existente.precoBase = item.precoBase;
      existente.unidade = item.unidade;
    }
  }
  return [...mapa.values()];
}
